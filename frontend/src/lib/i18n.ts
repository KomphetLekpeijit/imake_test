export type Language = 'th' | 'en';
export type TranslationKey = typeof translations.th;

export function t(lang: Language, path: string): string {
  const keys = path.split('.');
  let result: any = translations[lang];
  for (const key of keys) {
    result = result?.[key];
  }
  return result || path;
}

